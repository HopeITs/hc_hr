<?php

namespace App\Console\Commands;

use App\Models\Position;
use Illuminate\Console\Command;

class FixPositionEmployeeCounts extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'positions:fix-counts';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Recalculate and fix exist_emp values in positions based on active contracts';

    /**
     * Execute the console command.
     */
    public function handle()
    {
        $this->info('Starting to fix position employee counts...');

        $fixedCount = 0;

        // Use chunkById for memory efficiency if you have thousands of positions
        // withCount() gets the count of ONLY active contracts directly from the database
        Position::withCount(['contracts' => function ($query) {
            $query->where('is_active', true);
        }])->chunkById(100, function ($positions) use (&$fixedCount) {

            foreach ($positions as $position) {
                // $position->contracts_count is automatically generated by withCount()

                // Only update if the current value is incorrect to save DB queries
                if ($position->exist_emp !== $position->contracts_count) {
                    $max = $position->contracts_count > $position->max_emp ? $position->contracts_count : $position->max_emp;

                    $position->update([
                        'exist_emp' => $position->contracts_count,
                        'max_emp' => $max,
                    ]);

                    $fixedCount++;

                    $this->line("Fixed Position ID: {$position->id} | Old Value: {$position->exist_emp} | New Value: {$position->contracts_count}");
                }
            }
        });

        $this->newLine();
        $this->info("Done! Successfully fixed exist_emp for {$fixedCount} positions.");
    }
}
