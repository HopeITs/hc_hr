    /** Width of the text at 1px font size. */
    public static function width(string $text, int $weight = 400): float
    {
        $table = self::WIDTHS[$weight] ?? self::WIDTHS[400];
        $width = 0.0;

        foreach (mb_str_split($text) as $character) {
            $width += $table[$character] ?? self::FALLBACK;
        }

        return $width;
    }
